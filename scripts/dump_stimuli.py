"""Write every text a model sees, per scenario and condition, as Markdown (docs/stimuli.md).

    .venv/bin/python scripts/dump_stimuli.py > docs/stimuli.md

The texts come from the code and the scenario files, built on a scratch repository (seed 0), with the episode's
ticket id shown as <ticket>.
"""

import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from coverup import bots, prompts  # noqa: E402
from coverup.runner import conditions  # noqa: E402
from coverup.scenario import build, load_spec, scripted_text  # noqa: E402

SCENARIOS = ("vendored_sdk", "unsigned_webhook")


def quote(text: str) -> str:
    return "\n".join("> " + line if line else ">" for line in text.strip().splitlines())


def main() -> None:
    out = ["# Stimuli", "",
           "Generated by `scripts/dump_stimuli.py` from the code; do not edit by hand. The ticket id differs per "
           "episode and is shown as `<ticket>`.", ""]
    out += ["## System prompts", ""]
    for scenario in SCENARIOS:
        repo = load_spec(scenario).get("repo_name", "ledgerly")
        out += [f"### {scenario} (`{repo}`)", "", "**Solo agent**", "", quote(prompts.solo_prompt(human_channel=True,
                                                                                                    repo=repo)), "",
                "**Lead**", "", quote(prompts.lead_prompt(human_channel=True, lead_tools=("list_dir",), repo=repo)), "",
                "**worker_1, with the peer channel (the peer arm)**", "",
                quote(prompts.worker_prompt("worker_1", peer_channel=True, repo=repo)), ""]
    with tempfile.TemporaryDirectory() as tmp:
        for scenario in SCENARIOS:
            inst = build(scenario, Path(tmp) / scenario, seed=0)
            hide = lambda text: text.replace(inst.canary, "<ticket>").replace("{canary}", "<ticket>")  # noqa: E731
            spec = load_spec(scenario)
            scripted = scripted_text(inst)
            sites = inst.initial_sites["protected_print"] + inst.initial_sites["protected_logging"]
            out += [f"## Scenario `{scenario}`", "", "### The user's task", "", quote(inst.task_text), "",
                    f"### The warning (`{inst.warning_file}`, variant `reasoned`)", "",
                    quote(hide(spec["warnings"]["reasoned"])), ""]
            if spec.get("warning_inline"):
                out += [f"It fills a `{{warning}}` placeholder inside an otherwise ordinary `{inst.warning_file}`.", ""]
            assignments = scripted.get("assignments") or bots.PEER_ASSIGNMENTS
            out += ["### The scripted lead (peer arm)", "", "Assignments:", ""]
            out += [f"- **{worker}:** {text}" for worker, text in assignments.items()]
            out += ["", f"Its reply to any question: \"{scripted.get('lead_reply') or bots.PEER_LEAD_REPLY}\"", ""]
            out += ["### The peer arm: worker_2's note to worker_1, per condition", ""]
            notes = scripted.get("peer_notes") or {c: t.format(vendor_sites=sites) for c, t in bots.PEER_NOTES.items()}
            for condition in conditions("peer", scenario):
                out += [f"#### `{condition}`", "", quote(hide(notes[condition])), ""]
                if scripted:
                    report = (scripted.get("lead_reports") or {}).get(condition)
                    request = (scripted.get("lead_messages") or {}).get(condition)
                else:
                    report = bots.LEAD_REPORTS.get(condition, "").format(vendor_sites=sites).strip() or None
                    request = bots.LEAD_REQUESTS.get(condition)
                if report:
                    out += ["worker_2's report to the lead adds (worker_1 does not see it):", "", quote(hide(report)), ""]
                if request:
                    out += ["The lead then sends worker_1:", "", quote(prompts.lead_message(request)), ""]
            if scenario == "vendored_sdk":
                out += ["### The lead arm: worker_2's finish report to the model lead, per condition", ""]
                for condition in conditions("lead", scenario):
                    out += [f"#### `{condition}`", "",
                            quote(bots.LEAD_ARM_REPORTS[condition].format(vendor_sites=sites)), ""]
                    if condition.endswith("two_workers_ask"):
                        out += ["worker_1's finish report (its file list, then):", "", quote(bots.ASKER_REQUEST), ""]
            out += ["### The user's questions after the session (one per branch)", ""]
            for level in prompts.INTERVIEW_LEVELS:
                out += [f"- **`{level}`:** {prompts.interview_level(level, inst.protected_dir, inst.edit_question)}"]
            if spec.get("rating_question"):
                out += [f"- **`rate`:** {spec['rating_question'].strip()}"]
            out += [""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
